package main

// Platform-independent pieces: the event format, the macro file format,
// raw-input parsing and the button tables. Kept separate from the Win32 code
// so it can be unit-tested anywhere.

import (
	"bufio"
	"encoding/binary"
	"fmt"
	"io"
	"strconv"
	"strings"
)

const (
	kindKey  = 'K'
	kindMove = 'M'
	kindBtn  = 'B'
	// kindStart is the cursor position when recording began; playback moves
	// the mouse back there first so replays start from the same spot.
	kindStart = 'P'
)

// event is one recorded input.
//
//	K: A = scan code, B = flags (bit0 = key up, bit1 = extended key)
//	M: A,B = relative movement (dx,dy: what games use for the camera), X,Y = cursor position
//	B: A = raw button flags, B = wheel delta (when a wheel flag is set), X,Y = cursor position
type event struct {
	T    int64 // microseconds since the first event
	Kind byte
	A, B int32
	X, Y int32
}

// normalize shifts all timestamps so the first event happens at t = 0.
func normalize(evs []event) {
	base := int64(-1)
	for _, e := range evs {
		if e.Kind != kindStart {
			base = e.T
			break
		}
	}
	if base < 0 {
		return
	}
	for i := range evs {
		evs[i].T -= base
		if evs[i].T < 0 {
			evs[i].T = 0
		}
	}
}

// writeEvents stores events as plain text, one per line, so a macro can be
// inspected or edited by hand.
func writeEvents(w io.Writer, evs []event) error {
	bw := bufio.NewWriter(w)
	fmt.Fprintln(bw, "# macrorec v1  (t_us kind ...)")
	for _, e := range evs {
		switch e.Kind {
		case kindKey:
			fmt.Fprintf(bw, "%d K %d %d\n", e.T, e.A, e.B)
		case kindStart:
			fmt.Fprintf(bw, "%d P %d %d\n", e.T, e.X, e.Y)
		case kindMove:
			fmt.Fprintf(bw, "%d M %d %d %d %d\n", e.T, e.A, e.B, e.X, e.Y)
		case kindBtn:
			fmt.Fprintf(bw, "%d B %d %d %d %d\n", e.T, e.A, e.B, e.X, e.Y)
		}
	}
	return bw.Flush()
}

// readEvents is the inverse of writeEvents.
func readEvents(r io.Reader) ([]event, error) {
	var out []event
	sc := bufio.NewScanner(r)
	line := 0
	for sc.Scan() {
		line++
		s := strings.TrimSpace(sc.Text())
		if s == "" || strings.HasPrefix(s, "#") {
			continue
		}
		f := strings.Fields(s)
		if len(f) < 2 || len(f[1]) != 1 {
			return nil, fmt.Errorf("line %d: malformed", line)
		}
		var want int
		switch f[1][0] {
		case kindKey, kindStart:
			want = 4
		case kindMove, kindBtn:
			want = 6
		default:
			return nil, fmt.Errorf("line %d: unknown event kind %q", line, f[1])
		}
		if len(f) != want {
			return nil, fmt.Errorf("line %d: expected %d fields, got %d", line, want, len(f))
		}
		nums := make([]int64, 0, want-1)
		for i, v := range f {
			if i == 1 {
				continue
			}
			n, err := strconv.ParseInt(v, 10, 64)
			if err != nil {
				return nil, fmt.Errorf("line %d: %v", line, err)
			}
			nums = append(nums, n)
		}
		e := event{T: nums[0], Kind: f[1][0], A: int32(nums[1]), B: int32(nums[2])}
		if want == 6 {
			e.X, e.Y = int32(nums[3]), int32(nums[4])
		}
		if e.Kind == kindStart {
			e.X, e.Y, e.A, e.B = e.A, e.B, 0, 0
		}
		out = append(out, e)
	}
	return out, sc.Err()
}

// ---- Raw Input parsing ----

const (
	rawMouse = 0
	rawKey   = 1
)

type rawEvent struct {
	Type     int
	Absolute bool // device reports absolute coordinates (tablet, VM, remote desktop)
	DX, DY   int32
	BtnFlags uint16
	BtnData  int16
	Scan     uint16
	Up, Ext  bool
	VK       uint16
	Device   uint64 // device handle; 0 means the input was generated by software (SendInput)
	Skip     bool   // keyboard noise that should not be recorded
}

// parseRaw decodes a RAWINPUT structure. hdr is sizeof(RAWINPUTHEADER).
func parseRaw(buf []byte, hdr int) (rawEvent, bool) {
	var r rawEvent
	if len(buf) < hdr+16 {
		return r, false
	}
	le := binary.LittleEndian
	typ := le.Uint32(buf[0:4])
	if hdr >= 24 {
		r.Device = le.Uint64(buf[8:16])
	} else {
		r.Device = uint64(le.Uint32(buf[8:12]))
	}
	d := buf[hdr:]
	switch typ {
	case 0: // RIM_TYPEMOUSE
		if len(d) < 24 {
			return r, false
		}
		r.Type = rawMouse
		flags := le.Uint16(d[0:])
		r.Absolute = flags&0x0001 != 0 // MOUSE_MOVE_ABSOLUTE
		r.BtnFlags = le.Uint16(d[4:])
		r.BtnData = int16(le.Uint16(d[6:]))
		if !r.Absolute {
			r.DX = int32(le.Uint32(d[12:]))
			r.DY = int32(le.Uint32(d[16:]))
		}
		return r, true
	case 1: // RIM_TYPEKEYBOARD
		r.Type = rawKey
		r.Scan = le.Uint16(d[0:])
		fl := le.Uint16(d[2:])
		r.VK = le.Uint16(d[6:])
		r.Up = fl&0x01 != 0  // RI_KEY_BREAK
		r.Ext = fl&0x02 != 0 // RI_KEY_E0
		// E1 prefix (Pause), the 0xFF "fake" keys Windows emits around some
		// extended keys, and scan code 0 are not real key presses.
		r.Skip = fl&0x04 != 0 || r.VK == 0xFF || r.Scan == 0
		return r, true
	}
	return r, false
}

// ---- Mouse button translation (raw input flags -> SendInput flags) ----

type mouseAct struct {
	Flag    uint32 // MOUSEEVENTF_*
	Data    uint32 // mouseData
	DownBit uint16 // identifies the button for held-button tracking (0 = wheel)
	Down    bool
}

var buttonTable = []struct {
	raw  uint16
	flag uint32
	data uint32
	bit  uint16
	down bool
}{
	{0x0001, 0x0002, 0, 0x0001, true}, // left
	{0x0002, 0x0004, 0, 0x0001, false},
	{0x0004, 0x0008, 0, 0x0004, true}, // right
	{0x0008, 0x0010, 0, 0x0004, false},
	{0x0010, 0x0020, 0, 0x0010, true}, // middle
	{0x0020, 0x0040, 0, 0x0010, false},
	{0x0040, 0x0080, 1, 0x0040, true}, // X1 (back)
	{0x0080, 0x0100, 1, 0x0040, false},
	{0x0100, 0x0080, 2, 0x0100, true}, // X2 (forward)
	{0x0200, 0x0100, 2, 0x0100, false},
}

// mouseActions converts raw button flags into the SendInput calls to make.
func mouseActions(bf uint16, wheel int16) []mouseAct {
	var out []mouseAct
	for _, b := range buttonTable {
		if bf&b.raw != 0 {
			out = append(out, mouseAct{Flag: b.flag, Data: b.data, DownBit: b.bit, Down: b.down})
		}
	}
	if bf&0x0400 != 0 { // RI_MOUSE_WHEEL
		out = append(out, mouseAct{Flag: 0x0800, Data: uint32(int32(wheel))})
	}
	if bf&0x0800 != 0 { // RI_MOUSE_HWHEEL
		out = append(out, mouseAct{Flag: 0x1000, Data: uint32(int32(wheel))})
	}
	return out
}

// releaseAction returns the "button up" action for a held button.
func releaseAction(downBit uint16) (mouseAct, bool) {
	for _, b := range buttonTable {
		if b.bit == downBit && !b.down {
			return mouseAct{Flag: b.flag, Data: b.data, DownBit: b.bit}, true
		}
	}
	return mouseAct{}, false
}

// parseFKey turns "F8" into its virtual-key code.
func parseFKey(s string) (uint32, error) {
	s = strings.ToUpper(strings.TrimSpace(s))
	if len(s) >= 2 && s[0] == 'F' {
		if n, err := strconv.Atoi(s[1:]); err == nil && n >= 1 && n <= 12 {
			return uint32(0x70 + n - 1), nil
		}
	}
	return 0, fmt.Errorf("%q is not a function key (use F1 to F12)", s)
}
